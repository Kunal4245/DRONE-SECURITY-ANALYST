# Define tools list
tools = [analyze_frame, query_events, generate_daily_summary]

# Agent prompt with memory support
agent_prompt = ChatPromptTemplate.from_messages([
    ("system", """You are a Drone Security Analyst Agent. You help property owners 
monitor their property using drone surveillance video footage analyzed by AI. You can:

1. Analyze drone camera frames for security threats using the analyze_frame tool
2. Query past security events using the query_events tool  
3. Generate video/daily security summaries using the generate_daily_summary tool

The system processes real drone video footage:
- A Vision AI (VLM) first describes what it sees in each video frame
- Then you analyze those descriptions for security threats

When the user asks about specific events or objects, use the query_events tool.
When asked to summarize, use the generate_daily_summary tool.
Always provide clear, actionable security insights."""),
    MessagesPlaceholder(variable_name="chat_history"),
    ("human", "{input}"),
    MessagesPlaceholder(variable_name="agent_scratchpad"),
])

# Memory for conversation context
memory = ConversationBufferWindowMemory(
    memory_key="chat_history",
    return_messages=True,
    k=10,
)

# Create the agent
agent = create_tool_calling_agent(llm, tools, agent_prompt)

# Create the executor
agent_executor = AgentExecutor(
    agent=agent,
    tools=tools,
    memory=memory,
    verbose=True,
    handle_parsing_errors=True,
    max_iterations=5,
)


def _is_summary_request(message: str) -> bool:
    """Return True when the user is asking for a summary or briefing."""
    message_lower = message.lower()
    summary_keywords = ["summary", "summarize", "briefing", "brief", "overview", "report"]
    return any(keyword in message_lower for keyword in summary_keywords)


def _is_event_query(message: str) -> bool:
    """Return True when the user is asking about prior events or incidents."""
    message_lower = message.lower()
    query_keywords = [
        "incident", "incidents", "event", "events", "alert", "alerts",
        "midnight", "night", "truck", "vehicle", "person", "perimeter",
        "gate", "garage", "fence", "critical", "high", "medium", "low",
        "what happened", "who", "where", "when", "show", "find",
    ]
    return any(keyword in message_lower for keyword in query_keywords)


def _recent_event_context(limit: int = 8) -> str:
    """Build a compact context block from the most recent indexed frames."""
    frames = indexer.get_all_frames()
    if not frames:
        return "No indexed frames are available yet."

    recent_frames = frames[-limit:]
    lines = []
    for frame in recent_frames:
        detected_objects = frame.get("detected_objects", [])
        if isinstance(detected_objects, list):
            detected_objects_text = ", ".join(detected_objects) if detected_objects else "none"
        else:
            detected_objects_text = str(detected_objects)

        lines.append(
            f"- {frame.get('timestamp', 'unknown time')} | {frame.get('location', 'unknown location')} | "
            f"Risk: {frame.get('risk_level', 'Low')} | Summary: {frame.get('event_summary', '')} | "
            f"Objects: {detected_objects_text}"
        )

    return "\n".join(lines)


def analyze_single_frame(frame: dict) -> dict:
    """
    Analyze a single frame — convenience function that bypasses the agent
    and directly calls the analysis logic for streaming use cases.
    
    For the video pipeline, the frame dict should already have 'vlm_description'
    populated by the VLM module.
    
    Args:
        frame: Frame dictionary with VLM description and telemetry.
    
    Returns:
        Parsed analysis result dictionary.
    """
    result_json = analyze_frame.invoke(json.dumps(frame))
    try:
        return json.loads(result_json)
    except json.JSONDecodeError:
        return {"error": "Failed to parse analysis result", "raw": result_json}


def chat(message: str) -> str:
    """
    Send a chat message to the agent and get a response.
    Maintains conversation context through memory.
    """
    try:
        if _is_summary_request(message):
            return generate_daily_summary.invoke("")

        if _is_event_query(message):
            query_result = query_events.invoke(message)
            answer_prompt = f"""User question: {message}

Indexed event data:
{query_result}

Answer the user's question in plain English using the event data above. If the result is empty, say no matching event was found."""

            response = llm.invoke([
                SystemMessage(content=CHAT_ASSISTANT_PROMPT),
                HumanMessage(content=answer_prompt),
            ])
            return _content_to_text(response.content)

        context = _recent_event_context()
        direct_prompt = f"""Recent indexed events:
{context}

User question: {message}

Respond directly and concisely. If the question is about recent security activity, use the indexed events above."""

        response = llm.invoke([
            SystemMessage(content=CHAT_ASSISTANT_PROMPT),
            HumanMessage(content=direct_prompt),
        ])
        return _content_to_text(response.content)
    except Exception as e:
        try:
            result = agent_executor.invoke({"input": message})
            return result.get("output", "No response generated.")
        except Exception as fallback_error:
            return f"Error: {str(fallback_error)}"


def reset_memory():
    """Clear the agent's conversation memory."""
    memory.clear()
