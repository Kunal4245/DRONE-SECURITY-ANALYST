@tool
def analyze_frame(frame_json: str) -> str:
    """Analyze a drone surveillance frame for security threats.

    Takes a JSON string containing frame data including VLM description,
    telemetry, and optionally rule flags. Performs security risk assessment.

    Args:
        frame_json: JSON string with frame_id, timestamp, location, altitude,
                    description (from VLM), vlm_description, and optionally rule_flags.
    """
    try:
        frame = json.loads(frame_json)
    except json.JSONDecodeError:
        return json.dumps({"error": "Invalid JSON input"})

    # Use VLM description if available, otherwise use original description
    description = frame.get("vlm_description") or frame.get("description", "No description available")

    # Create a modified frame dict with the VLM description for alert engine
    frame_for_rules = {**frame, "description": description}

    # Get rule-based flags
    flags = alert_engine.evaluate_rules(frame_for_rules)
    suggested_risk = alert_engine.get_suggested_risk_level(flags)

    # Build the analysis prompt
    analysis_prompt = f"""Analyze this drone surveillance frame:

Frame ID: {frame.get('frame_id')}
Timestamp: {frame.get('timestamp')}
Location: {frame.get('location')}
Drone Altitude: {frame.get('altitude', 'N/A')}m
GPS: ({frame.get('drone_lat', 'N/A')}, {frame.get('drone_lon', 'N/A')})

VLM Camera Description (what the Vision AI sees in the actual drone image):
"{description}"

Pre-filter flags: {', '.join(flags) if flags else 'None'}
Suggested minimum risk level: {suggested_risk}

Based on the security rules, analyze this frame and return a JSON object."""

    response_text = ""

    try:
        response = llm.invoke([
            SystemMessage(content=SECURITY_ANALYST_PROMPT),
            HumanMessage(content=analysis_prompt),
        ])

        # Parse the AI response
        response_text = _content_to_text(response.content)
        # Clean up potential markdown formatting
        if response_text.startswith("```"):
            lines = response_text.split("\n")
            response_text = "\n".join(lines[1:-1])

        analysis = json.loads(response_text)

        # Ensure minimum risk level from rules
        risk_hierarchy = {"Low": 0, "Medium": 1, "High": 2, "Critical": 3}
        ai_risk = risk_hierarchy.get(analysis.get("risk_level", "Low"), 0)
        rule_risk = risk_hierarchy.get(suggested_risk, 0)
        if rule_risk > ai_risk:
            analysis["risk_level"] = suggested_risk

        # Store in database
        db_entry = {
            "frame_id": frame.get("frame_id"),
            "timestamp": frame.get("timestamp"),
            "location": frame.get("location"),
            "description": description,
            "detected_objects": analysis.get("detected_objects", []),
            "risk_level": analysis.get("risk_level", "Low"),
            "alert_message": analysis.get("alert_message", ""),
            "event_summary": analysis.get("event_summary", ""),
            "image_path": frame.get("image_filename", ""),
            "vlm_description": description,
            "video_source": frame.get("video_source", ""),
        }
        indexer.insert_frame(db_entry)

        # Add extra info to the response
        analysis["rule_flags"] = flags
        analysis["frame_id"] = frame.get("frame_id")
        analysis["timestamp"] = frame.get("timestamp")
        analysis["location"] = frame.get("location")
        analysis["vlm_description"] = description

        return json.dumps(analysis, indent=2)

    except json.JSONDecodeError:
        # If AI response isn't valid JSON, create a structured response
        fallback = {
            "detected_objects": [],
            "event_summary": response_text if 'response_text' in dir() else "Analysis failed",
            "risk_level": suggested_risk,
            "alert_message": f"ALERT: {suggested_risk} risk detected at {frame.get('location')}",
            "reasoning": "AI response parsing failed, using rule-based assessment",
            "rule_flags": flags,
            "frame_id": frame.get("frame_id"),
            "timestamp": frame.get("timestamp"),
            "location": frame.get("location"),
            "vlm_description": description,
        }
        db_entry = {
            "frame_id": frame.get("frame_id"),
            "timestamp": frame.get("timestamp"),
            "location": frame.get("location"),
            "description": description,
            "detected_objects": [],
            "risk_level": suggested_risk,
            "alert_message": fallback["alert_message"],
            "event_summary": fallback["event_summary"],
            "image_path": frame.get("image_filename", ""),
            "vlm_description": description,
            "video_source": frame.get("video_source", ""),
        }
        indexer.insert_frame(db_entry)
        return json.dumps(fallback, indent=2)

    except Exception as e:
        return json.dumps({"error": str(e)})


@tool
def query_events(query: str) -> str:
    """Query indexed security events using natural language.
    
    Supports queries like:
    - "show all truck events"
    - "what happened after midnight"  
    - "show critical alerts"
    - "events at the main gate"
    
    Args:
        query: Natural language query about security events.
    """
    query_lower = query.lower()
    results = []

    # Detect query type and route to appropriate indexer function
    risk_keywords = {"critical": "Critical", "high": "High", "medium": "Medium", "low": "Low"}
    for keyword, level in risk_keywords.items():
        if keyword in query_lower:
            results = indexer.query_by_risk(level)
            if results:
                return json.dumps({
                    "query_type": "risk_filter",
                    "risk_level": level,
                    "count": len(results),
                    "results": results
                }, indent=2)

    # Time-based queries
    time_keywords = {
        "midnight": ("2024-01-16 00:00:00", "2024-01-16 01:00:00"),
        "after midnight": ("2024-01-16 00:00:00", "2024-01-16 06:00:00"),
        "night": ("2024-01-15 22:00:00", "2024-01-16 06:00:00"),
        "morning": ("2024-01-15 06:00:00", "2024-01-15 12:00:00"),
        "afternoon": ("2024-01-15 12:00:00", "2024-01-15 18:00:00"),
        "evening": ("2024-01-15 18:00:00", "2024-01-15 22:00:00"),
    }
    for keyword, (start, end) in time_keywords.items():
        if keyword in query_lower:
            results = indexer.query_by_time_range(start, end)
            if results:
                return json.dumps({
                    "query_type": "time_range",
                    "period": keyword,
                    "count": len(results),
                    "results": results
                }, indent=2)

    # Object-based queries
    object_keywords = [
        "truck", "sedan", "vehicle", "car", "f150", "person", "people",
        "guard", "courier", "employee", "badge", "gate", "fence", "garage",
        "parking", "perimeter", "door", "hoodie", "hooded", "building",
        "tree", "road", "field",
    ]
    for keyword in object_keywords:
        if keyword in query_lower:
            results = indexer.query_by_object(keyword)
            if results:
                return json.dumps({
                    "query_type": "object_search",
                    "keyword": keyword,
                    "count": len(results),
                    "results": results
                }, indent=2)

    # Fallback: return all frames
    all_frames = indexer.get_all_frames()
    return json.dumps({
        "query_type": "all_frames",
        "count": len(all_frames),
        "results": all_frames
    }, indent=2)


@tool
def generate_daily_summary() -> str:
    """Generate a comprehensive security summary from all indexed frames.
    
    Fetches all stored frame events (from video analysis) and uses AI to
    generate a 4-5 sentence summary of the security activity, including
    key incidents, threat patterns, and recommendations.
    """
    all_frames = indexer.get_all_frames()

    if not all_frames:
        return "No frames have been analyzed yet. Process a video first."

    # Build context for the summary
    frame_summaries = []
    for f in all_frames:
        vlm_desc = f.get("vlm_description", "")
        frame_summaries.append(
            f"[{f['timestamp']}] {f['location']}: {f['event_summary']} "
            f"(Risk: {f['risk_level']}) "
            f"[VLM saw: {vlm_desc[:100]}...]" if vlm_desc else
            f"[{f['timestamp']}] {f['location']}: {f['event_summary']} "
            f"(Risk: {f['risk_level']})"
        )

    video_source = all_frames[0].get("video_source", "unknown source")

    summary_prompt = f"""Based on these drone surveillance events from analyzing video "{video_source}",
generate a 4-5 sentence security summary for the property owner.

Total frames analyzed: {len(all_frames)}
Events:
{chr(10).join(frame_summaries)}

Include:
1. Overall security status for the monitoring period
2. Key incidents and their severity  
3. Patterns or concerns detected by the drone camera
4. Recommended actions for the property owner

Write the summary in a professional security report style."""

    try:
        response = llm.invoke([
            SystemMessage(content="You are a professional security analyst writing a daily briefing based on drone surveillance footage analysis."),
            HumanMessage(content=summary_prompt),
        ])
        return _content_to_text(response.content)
    except Exception as e:
        return f"Error generating summary: {str(e)}"


